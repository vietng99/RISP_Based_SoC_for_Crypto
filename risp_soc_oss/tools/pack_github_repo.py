HEADERS_TCL = '''# Module references need every `include target in the project: add the headers as
# Verilog Header so Vivado resolves them and does not compile them on their own.
set hdrs [list \\
@HDRS@ \\
]
add_files -norecurse -fileset sources_1 $hdrs
set_property file_type {Verilog Header} [get_files $hdrs]
'''

CVA6_TCL = '''# CVA6 memories: synthesis uses the FPGA RAM (tc_sram_fpga_wrapper + SyncSpRamBeNx64);
# tc_sram_wrapper.sv is the simulation model (its body is translate_off, so synthesis
# would see an empty module and make it a black box).
set synth_only [list \\
@SYNTH_ONLY@ \\
]
add_files -norecurse -fileset sources_1 $synth_only
set_property used_in_simulation false [get_files $synth_only]
set_property used_in_synthesis false [get_files [list \\
@SIM_ONLY@ \\
]]
# common_cells unread.sv has a body only under TARGET_VIVADO (an empty module is a black box).
# Synthesis only: in xsim that body would drive X onto the instance input.
set_property -name {STEPS.SYNTH_DESIGN.ARGS.MORE OPTIONS} -value {@SYNTH_OPTS@} -objects [get_runs synth_1]
'''

SET_TEST = bd.SET_TEST.replace("# [core_soc block design] set_test", "# set_test").replace(
    "#   source <package>/scripts/set_test.tcl      (create_project.tcl already does this)",
    "#   source <repo>/scripts/set_test.tcl      (create_project.tcl already does this)")


def main(out):
    repo = Path(out) / REPO
    if repo.exists():
        shutil.rmtree(repo)
    repo.mkdir(parents=True)
    placed = {}  # repo path -> source path

    def put(src, dst):
        src = Path(src).resolve()
        if dst in placed:
            if placed[dst] != src:
                raise SystemExit(f"two sources for {dst}: {placed[dst]} and {src}")
            return
        placed[dst] = src
        (repo / dst).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(src, repo / dst)

    summary = []
    for core in CORES:
        srcs, incs = bd.bd_sources(core)
        srcs = [Path(s).resolve() for s in srcs]
        incs = [Path(d).resolve() for d in incs]
        hdrs, missing = headers(srcs, incs)
        names = [dest(f) for f in srcs]
        for f, n in zip(srcs, names):
            put(f, n)
        hnames = [dest(h) for h in hdrs]
        for h, n in zip(hdrs, hnames):
            put(h, n)
        incnames = [dest(d / "x").parent for d in incs]
        incnames = [d for d in incnames if any(n.parent == d or d in n.parents for n in hnames)]
        extra = ""
        if core == "cva6":
            so = [dest(f) for f in CVA6_SYNTH_ONLY]
            for f, n in zip(CVA6_SYNTH_ONLY, so):
                put(f, n)
            sim_only = [dest(f) for f in CVA6_SIM_ONLY]
            assert all(n in names for n in sim_only)
            extra = (CVA6_TCL.replace("@SYNTH_ONLY@", tcl_list(so))
                     .replace("@SIM_ONLY@", tcl_list(sim_only))
                     .replace("@SYNTH_OPTS@", SYNTH_OPTS["cva6"]))
        name = f"{core}_soc"
        tcl = (TCL.replace("@NAME@", name).replace("@CELL@", bd.CPU_CELL[core])
               .replace("@TITLE@", TITLE[core])
               .replace("@PART@", pv.PART).replace("@BOARD@", pv.BOARD)
               .replace("@DEFS@", " ".join(pv.DEFINES.get(core, [])))
               .replace("@SYNTH_DEFS@", " ".join(SYNTH_DEFS.get(core, [])))
               .replace("@SIM_DEFS@", " ".join(SIM_DEFS.get(core, [])))
               .replace("@SOURCES@", tcl_list(names))
               .replace("@INCS@", tcl_list(incnames))
               .replace("@HEADERS@", HEADERS_TCL.replace("@HDRS@", tcl_list(hnames)) if hnames else "")
               .replace("@CORE_EXTRA@", extra)
               .replace("@TBS@", tcl_list([Path("tb") / f"{tb}.v" for tb in sorted({t for _, t in bd.TESTS})])))
        (repo / "socs" / name).mkdir(parents=True)
        (repo / "socs" / name / "create_project.tcl").write_text(tcl)
        # file list for other tools (Verilator, Yosys, ...): simulation view, paths from the repo root
        fl = [f"// {name}: {SOC_DESC[core]}. Paths are relative to the repository root.",
              "// Simulation view: CPU, cpu_core wrapper and the AES/SHA3/RSA accelerators."]
        if core == "cva6":
            fl.append("// For synthesis replace tc_sram_wrapper.sv with the two FPGA RAM files"
                      " (see create_project.tcl).")
        fl += [f"+incdir+{d.as_posix()}" for d in incnames]
        fl += [f"+define+{d}" for d in pv.DEFINES.get(core, [])]
        fl += [n.as_posix() for n in names]
        (repo / "socs" / name / "filelist.f").write_text("\n".join(fl) + "\n")
        summary.append((name, len(names), len(hnames), sorted(missing)))

    # Ibex: BUFGCE SIM_DEVICE follows the part (same patch as the Vivado packages)
    pv.patch_ibex(repo / "rtl/cpu/ibex/ibex_axi_top_combined.sv")
    # fix 2: instr_tracer off unless CVA6_INSTR_TRACER is defined
    cva6 = repo / "third_party/cva6/core/cva6.sv"
    text = cva6.read_text()
    assert text.count(TRACER_OLD) == 1
    cva6.write_text(text.replace(TRACER_OLD, TRACER_NEW))

    # licenses of every third-party tree a copied file sits in
    for dst, src in list(placed.items()):
        if dst.parts[0] != "third_party":
            continue
        d, top = src.parent, TP
        while d != top and top in d.parents:
            for lic in d.glob("LICENSE*"):
                put(lic, dest(lic))
            d = d.parent
    for src, dst in EXTRA_LICENSES.items():
        put(src, Path(dst))

    # testbenches, firmware, constraints, set_test
    for tb in sorted({t for _, t in bd.TESTS}):
        put(TB_SRC / f"{tb}.v", Path("tb") / f"{tb}.v")
    for name, _ in bd.TESTS:
        for ext in FW_EXT:
            put(FW_SRC / f"{name}{ext}", Path("firmware") / f"{name}{ext}")
    for f in FW_COMMON:
        put(FW_SRC / f, Path("firmware") / f)
    (repo / "constraints").mkdir()
    (repo / "constraints/soc.xdc").write_text(
        "# clk_wiz_0 constrains its own 100 MHz input and derives clk_out1 (40 MHz).\n"
        "# For fmax: change clk_wiz_0 CLKOUT1_REQUESTED_OUT_FREQ, re-run implementation, read WNS.\n"
        "set_false_path -from [get_ports reset_0]\n"
        "set_false_path -from [get_ports UART_0_rxd]\n"
        "set_false_path -to [get_ports UART_0_txd]\n")
    (repo / "scripts").mkdir()
    (repo / "scripts/set_test.tcl").write_text(
        SET_TEST.replace("@MAP@", "\n".join(f"    {n} {tb}" for n, tb in bd.TESTS)))
    docs = Path(__file__).with_name("github_repo")
    for f in docs.rglob("*"):
        if f.is_file():
            put(f, f.relative_to(docs))

    for path, old, new in COMMENT_FIXES:
        f = repo / path
        text = f.read_text()
        assert text.count(old) == 1, (path, old[:60])
        f.write_text(text.replace(old, new))

    for name, n, h, missing in summary:
        print(f"{name}: {n} sources, {h} headers, headers not found: {missing}")
    print(f"files: {sum(1 for f in repo.rglob('*') if f.is_file())}")


if __name__ == "__main__":
    main(sys.argv[1])
