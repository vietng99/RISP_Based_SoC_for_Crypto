def dest(f):
    f = Path(f).resolve()
    if f.parent == bd.BD_DIR.resolve() and f.name.startswith("cpu_core_"):
        return Path("rtl/cpu") / f.stem[len("cpu_core_"):] / f.name
    r = f.relative_to(PAPER).as_posix()
    for old, new, keep in LAYOUT:
        if r.startswith(old):
            rest = r[len(old):]
            return Path(new) / (rest if keep else Path(rest).name)
    raise SystemExit(f"no repo place for {r}")


def headers(srcs, incs):
    """Every header reached by `include from srcs (recursively), resolved like Vivado:
    the including file's directory first, then the include dirs in order."""
    found, todo, missing = [], list(srcs), set()
    while todo:
        f = todo.pop()
        for line in Path(f).read_text(errors="replace").splitlines():
            m = bd.INC_RE.match(line)
            if not m:
                continue
            hit = next((d / m.group(1) for d in [Path(f).parent, *incs] if (d / m.group(1)).is_file()), None)
            if hit is None:
                missing.add(m.group(1))
            elif hit not in found and hit not in srcs:
                found.append(hit)
                todo.append(hit)
    return found, missing


