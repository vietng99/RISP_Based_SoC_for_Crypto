#!/usr/bin/env python3
"""Write flist/cva6_soc.f: the RISSP SoC with CVA6 in place of rissp_top.

Sources:
  third_party/cva6/core/Flist.cva6 (+ hpdcache.Flist), CVA6 v5.3.0
  flist/rissp_soc.f minus the ip_repo/cpu_rissp files
  rtl/cores/common/*.sv, rtl/cores/cva6/*.sv

CVA6 vendors its own pulp common_cells and axi. The SoC already uses
third_party/common_cells v1.39.0 and third_party/axi v0.39.11; a module may
only be defined once, so every vendored file that also exists in the SoC copy
is taken from the SoC copy. The CVA6 config package is
rtl/cores/cva6/cva6_config_pkg_risp.sv (package cva6_config_pkg).

Usage: python3 tools/mk_cva6_flist.py   (from risp_soc_oss)
"""
import re
from pathlib import Path

OSS = Path(__file__).resolve().parent.parent
CVA6 = OSS / "third_party/cva6"
HPD = CVA6 / "core/cache_subsystem/hpdcache"
VENDOR_MAP = {
    "vendor/pulp-platform/common_cells/": OSS / "third_party/common_cells",
    "vendor/pulp-platform/axi/": OSS / "third_party/axi",
}
EXTRA_AXI = ["axi_demux_id_counters.sv", "axi_demux_simple.sv", "axi_demux.sv"]
EXTRA_CC = ["spill_register_flushable.sv", "spill_register.sv", "counter.sv", "delta_counter.sv",
            "onehot_to_bin.sv", "shift_reg_gated.sv", "id_queue.sv", "fall_through_register.sv", "stream_register.sv"]


def expand(flist: Path, env: dict) -> list:
    out = []
    for raw in flist.read_text().splitlines():
        line = raw.split("//")[0].strip()
        if not line:
            continue
        for k, v in env.items():
            line = line.replace("${%s}" % k, str(v))
        if line.startswith("-F "):
            out += expand(Path(line[3:].strip()), env)
        else:
            out.append(line)
    return out


def to_soc(path: str) -> str:
    """Map a CVA6-vendored pulp file or incdir onto the SoC copy when it exists."""
    for key, soc_root in VENDOR_MAP.items():
        i = path.find(key)
        if i < 0:
            continue
        rel = path[i + len(key):].rstrip("/")
        cand = soc_root / rel
        if cand.exists():
            return str(cand)
    return path


def main() -> None:
    env = {"CVA6_REPO_DIR": CVA6, "HPDCACHE_DIR": HPD, "TARGET_CFG": "@@CFG@@"}
    cva6 = expand(CVA6 / "core/Flist.cva6", env)

    lines, seen = [], set()

    def add(item: str) -> None:
        if item not in seen:
            seen.add(item)
            lines.append(item)

    # incdirs first (SoC pulp includes win over the vendored ones)
    add("+incdir+" + str(OSS / "third_party/common_cells/include"))
    add("+incdir+" + str(OSS / "third_party/axi/include"))
    for l in cva6:
        if l.startswith("+incdir+"):
            d = l[len("+incdir+"):]
            if "vendor/pulp-platform/common_cells" in d or "vendor/pulp-platform/axi" in d:
                continue
            add("+incdir+" + d.rstrip("/"))

    # packages and files used by the SoC copy of the pulp libs, then CVA6
    for f in ["common_cells/src/cf_math_pkg.sv", "axi/src/axi_pkg.sv"]:
        add(str(OSS / "third_party" / f))
    for l in cva6:
        if l.startswith("+"):
            continue
        if "@@CFG@@_config_pkg.sv" in l:
            add(str(OSS / "rtl/cores/cva6/cva6_config_pkg_risp.sv"))
            continue
        add(to_soc(l))
    for f in EXTRA_CC:
        p = OSS / "third_party/common_cells/src" / f
        if p.exists():
            add(str(p))
    for f in EXTRA_AXI:
        add(str(OSS / "third_party/axi/src" / f))

    # RISSP SoC without its CPU (keeps the SoC's own pulp files and order)
    rissp = expand(OSS / "flist/rissp_soc.f",
                   {"RISP_OSS": OSS, "RISP_IP": "${RISP_IP}"})
    for l in rissp:
        if "/cpu_rissp/" in l:
            continue
        if l.startswith("-f "):
            for m in expand(Path(l[3:].strip()), {"RISP_OSS": OSS}):
                add(m)
            continue
        add(l)

    for f in ["rtl/cores/common/axi_rom_bridge.sv", "rtl/cores/common/axi4_to_axil.sv",
              "rtl/cores/cva6/rissp_top_cva6.sv"]:
        add(str(OSS / f))

    out = OSS / "flist/cva6_soc.f"
    header = ["// RISSP SoC with CVA6 cv32a6_imac_sv0 as the CPU. Generated by tools/mk_cva6_flist.py.",
              "// Needs RISP_IP (= RISP/ip_repo)."]
    rel = [re.sub("^" + re.escape(str(OSS)), "${RISP_OSS}", l) if not l.startswith("+incdir+")
           else "+incdir+" + re.sub("^" + re.escape(str(OSS)), "${RISP_OSS}", l[8:]) for l in lines]
    out.write_text("\n".join(header + rel) + "\n")
    print(f"wrote {out} ({len(rel)} lines)")


if __name__ == "__main__":
    main()
